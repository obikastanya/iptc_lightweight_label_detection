"""Build the single-file paper jurnal_final/main.tex from the modular sources in src/paper/.

  * \\input{sections/...} and the table macros (\\TabMain, ...) are inlined;
  * \\rows{generated/tab_*} is replaced by the table rows written by the notebook (results/final/paper_generated/);
  * every \\val{key} is replaced by its literal value from results/final/paper_generated/numbers.tex;
  * only the figures that main.tex includes are copied from results/final/figures/ to jurnal_final/figures/;
  * results/final/paper_number_map.json records every key, its value, and how often it occurs, so that
    scripts/check_paper.py can report which literal numbers changed after the notebook is re-run.

jurnal_final/main.tex is meant to be edited by hand afterwards (the authors rewrite the text). To avoid
overwriting such edits, the build refuses to run when main.tex differs from the last build, unless --force.

Usage (from the project root):
    python scripts/build_paper.py [--compile] [--force]
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "paper"
GEN = ROOT / "results" / "final" / "paper_generated"
FIG_SRC = ROOT / "results" / "final" / "figures"
OUT = ROOT / "jurnal_final"
MAP = ROOT / "results" / "final" / "paper_number_map.json"
STATE = ROOT / "results" / "final" / "paper_build.json"
BS = chr(92)


def load_numbers() -> dict:
    values = {}
    for line in (GEN / "numbers.tex").read_text(encoding="utf8").splitlines():
        if "val@" in line and (BS + "endcsname{") in line:
            key = line.split("val@")[1].split(BS + "endcsname")[0]
            values[key] = line.split(BS + "endcsname{", 1)[1][:-1]
    return values


def read_body(path: Path) -> str:
    """File content without comment-only lines (the 'generated by' headers)."""
    return "\n".join(l for l in path.read_text(encoding="utf8").splitlines() if not l.lstrip().startswith("%"))


def inline_inputs(text: str) -> str:
    def repl(m):
        name = m.group(1)
        if name == "generated/numbers":
            return ""
        if name.startswith("generated/"):
            return read_body(GEN / f"{name.split('/', 1)[1]}.tex")
        return inline_inputs(read_body(SRC / f"{name}.tex"))
    return re.sub(re.escape(BS) + r"input\{([^}]+)\}", repl, text)


def matching_brace(text: str, start: int) -> int:
    """Index of the brace that closes the one at `start`."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{" and text[i - 1] != BS:
            depth += 1
        elif text[i] == "}" and text[i - 1] != BS:
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced braces")


def expand_table_macros(text: str) -> str:
    macros = {}
    pat = re.compile(re.escape(BS) + r"newcommand\{" + re.escape(BS) + r"(Tab[A-Za-z]+)\}\{")
    while (m := pat.search(text)):
        end = matching_brace(text, m.end() - 1)
        body = text[m.end():end]
        macros[m.group(1)] = body[1:] if body.startswith("%") else body
        text = text[:m.start()] + text[end + 1:]
    for name, body in macros.items():
        text = re.sub(re.escape(BS) + name + r"(?![A-Za-z])", lambda _: body.strip("\n"), text)
    return text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--compile", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    out_tex = OUT / "main.tex"
    if out_tex.exists() and STATE.exists() and not args.force:
        built = json.loads(STATE.read_text())["sha256"]
        if hashlib.sha256(out_tex.read_bytes()).hexdigest() != built:
            sys.exit(f"{out_tex} was edited after the last build; use --force to overwrite it "
                     "(or run scripts/check_paper.py to see which numbers changed)")

    values = load_numbers()
    text = read_body(SRC / "main.tex")
    text = inline_inputs(text)
    text = expand_table_macros(text)
    rows = re.compile(re.escape(BS) + r"rows\{generated/([^}]+)\}")
    text = rows.sub(lambda m: read_body(GEN / f"{m.group(1)}.tex"), text)

    used = {}
    def val(m):
        key = m.group(1)
        if key not in values:
            sys.exit(f"unknown number key: {key}")
        used[key] = used.get(key, 0) + 1
        return values[key]
    text = re.sub(re.escape(BS) + r"val\{([^}]+)\}", val, text)
    text = re.sub(re.escape(BS) + r"eng\{([^{}]*)\}", r"\1", text)

    # drop the helper definitions that the single file no longer needs
    text = text.replace(BS + "newcommand{" + BS + "eng}[1]{#1}\n", "")
    text = re.sub(re.escape(BS) + r"makeatletter\n" + re.escape(BS) + r"newcommand\{" + re.escape(BS)
                  + r"rows\}.*?\n" + re.escape(BS) + r"makeatother\n", "", text, flags=re.S)
    header = ("% =====================================================================\n"
              "% StaticKD -- single-file manuscript (IEEEtran journal layout)\n"
              "% Built by scripts/build_paper.py from src/paper/ and the notebook outputs; numbers are literal.\n"
              "% results/final/paper_number_map.json lists every number; scripts/check_paper.py reports changes.\n"
              "% Compile: pdflatex main && bibtex main && pdflatex main && pdflatex main\n"
              "% =====================================================================\n")
    text = header + text[text.index(BS + "documentclass"):]
    text = re.sub(r"\n{3,}", "\n\n", text)
    for leftover in (BS + "val{", BS + "rows{", BS + "input{", BS + "Tab"):
        if leftover in text:
            sys.exit(f"build left an unresolved {leftover!r}")

    OUT.mkdir(exist_ok=True)
    out_tex.write_text(text, encoding="utf8")
    figs = sorted(set(re.findall(r"includegraphics(?:\[[^\]]*\])?\{figures/([^}]+)\}", text)))
    fig_dir = OUT / "figures"
    fig_dir.mkdir(exist_ok=True)
    for old in fig_dir.iterdir():
        old.unlink()
    for f in figs:
        shutil.copy2(FIG_SRC / f, fig_dir / f)
    literal = {k: re.sub(re.escape(BS) + r"eng\{([^{}]*)\}", r"\1", values[k]) for k in used}  # as written in main.tex
    MAP.write_text(json.dumps({k: {"value": literal[k], "count": n} for k, n in sorted(used.items())},
                              indent=1, ensure_ascii=False), encoding="utf8")
    STATE.write_text(json.dumps({"sha256": hashlib.sha256(out_tex.read_bytes()).hexdigest()}))
    print(f"wrote {out_tex}: {len(used)} number keys, {sum(used.values())} numbers, {len(figs)} figures")
    if args.compile:
        for cmd in (["pdflatex", "-interaction=nonstopmode", "main"], ["bibtex", "main"],
                    ["pdflatex", "-interaction=nonstopmode", "main"], ["pdflatex", "-interaction=nonstopmode", "main"]):
            subprocess.run(cmd, cwd=OUT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        log = (OUT / "main.log").read_text(encoding="latin-1")
        print("compiled:", re.search(r"Output written on .*", log).group(0) if "Output written" in log else "FAILED")


if __name__ == "__main__":
    main()
